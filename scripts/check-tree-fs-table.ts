/**
 * The lead-tree gate's table (`scripts/check-tree-fs.ts`): every module in
 * `packages/server/src` and `packages/core/src` that can reach a file or
 * start a process, and how it stands toward a walled lead's folders. The
 * call sites behind each label are in
 * docs/architecture/lead-tree-containment.md, sections A–K.
 *
 * - `tree-fs`: reaches a lead's folder only through `PathGuards` or
 *   `tree-fs.ts` (and, for git, `git-contained.ts`).
 * - `refused-when-covered`: asks `covers` / `gitBarred` before any I/O and
 *   does nothing for a covered path.
 * - `spelling-only`: takes a `realpath` to compare spellings; every read or
 *   write after it goes through `tree-fs` (section G).
 * - `never-covered`: acts only inside a mount or the meetings home, which a
 *   covered folder never is (section F).
 * - `watch-only`: an `fs.watch` that reads no file (section H).
 * - `data-dir`: the server's own data folder.
 * - `owner-checkout`: the owner's own checkouts, prod's or the plugin
 *   cache, never a lead's folder.
 * - `not-in-inventory`: the inventory's grep found no path by which it acts
 *   on a lead's folder. A module added after this table was written gets a
 *   label someone chose for it, not this one.
 */
